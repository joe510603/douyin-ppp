"""触达停手时的提示文案 —— **飞书卡片和网页横幅共用同一份**

为什么单独抽一个模块（2026-11-28 实测踩出来的）
------------------------------------------------
抖音「取作品列表」这条路被降级时，提示分两种（判据是**证据**，不是猜）：

  · ``session``  主页压根没渲染出来（对照账号也打不开 → 整个会话被降级）
  · ``endpoint`` 会话正常、资料也拿得到，只有取作品这一条路没响应

11-27 改过一版文案，**只改了 ``worker.py``（飞书卡片）**，
``outreach_page.py``（网页横幅）没跟着改 →
用户在网页上看到的还是旧话（「它回 HTTP 200 但响应体是空的」），
飞书那边却是新话（「抖音不给我们作品列表了」）。
同一件事两套说法，还互相矛盾 —— 用户只会以为「系统乱了」。

所以规矩是：**停手文案只写在这里一处**，谁要显示都从这里拿。
要改口径就改这一个文件，飞书和网页同时变。

（横幅本身还有另一个独立的坑：旧停手记录过期后仍然挂着不放，
见 ``runner.last_risk_stop()`` —— 那是「横幅该不该显示」的问题，不是文案问题。）
"""

from __future__ import annotations

# 作品路走不通 → 标题 + 正文
#
# 正文里的「为什么必须停」是给用户看的**理由**，
# 不是给机器看的判断依据（机器看 ``diag`` 字段）。
_SESSION_TITLE = "🧱 抖音主页没渲染出来，触达已停手（**没有私信消耗你的线索**）"
_SESSION_BODY = (
    "**你的账号没问题，不用扫码，也不是验证码。**\n"
    "抖音给我们看的**主页是空壳**：标题在、正文只剩站点框架，\n"
    "作品列表的请求压根没发出来。\n"
    "（账号本身可能是好的——资料接口能查到这个人）\n\n"
    "为什么必须停：系统分不清「抓不到」和「这个人真的没作品」，\n"
    "以前会误判成「没作品」→ 改发私信 → **有作品的老客户被私信顶掉**。\n"
    "现在抓不到就把线索**退回队列**，一条都不消耗。\n\n"
    "怎么办：\n"
    "1. 等一会儿抖音自己恢复（一般几十分钟到几小时）\n"
    "2. 急着要的话**换个网络**（手机热点）再跑\n"
    "3. **别反复重试**——重试只会让限流拖得更久\n"
    "4. 已退回队列的线索，等恢复后会重新走**留言**（不再私信）"
)

_ENDPOINT_TITLE = "🧱 抖音不给我们作品列表了，触达已停手（**没有私信消耗你的线索**）"
_ENDPOINT_BODY = (
    "**你的账号没问题，不用扫码，也不是验证码。**\n"
    "抖音的「主页作品列表」这条路**不响应了**：\n"
    "页面连取作品的请求都不发（会话本身是正常的——\n"
    "对照的自家门店号主页能正常打开，资料也能拿到）。\n\n"
    "为什么必须停：系统分不清「抓不到」和「这个人真的没作品」，\n"
    "以前会误判成「没作品」→ 改发私信 → **有作品的老客户被私信顶掉**。\n"
    "现在抓不到就把线索**退回队列**，一条都不消耗。\n\n"
    "怎么办：\n"
    "1. 不用做任何事，等 30 分钟到几小时，它会自己恢复\n"
    "2. 急着要的话换个网络（手机热点）再跑\n"
    "3. **别反复重试**——重试只会让限流拖得更久\n"
    "4. 已退回队列的线索，等通道恢复后会重新走**留言**（不再私信）"
)


def works_stop_text(diag: str) -> tuple[str, str]:
    """作品路走不通时的提示文案 → ``(标题, 正文)``

    diag
    ----
    ``"session"``
        主页压根没渲染出来 → 对照账号也打不开 → 整个会话被降级。
    ``"endpoint"``
        会话正常（对照账号能打开、资料拿得到），只有取作品这条路没响应。
    其他/空
        归到 ``endpoint``：这个说法更保守 —— 只说「这一条路没响应」，
        不会在证据不足时断言「整个会话被降级」（那是更强的结论）。
    """
    if str(diag or "").strip().lower() == "session":
        return _SESSION_TITLE, _SESSION_BODY
    return _ENDPOINT_TITLE, _ENDPOINT_BODY
